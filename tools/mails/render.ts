// Renders the e-mails of supabase/functions/notify with sample data, without network and without sending anything.
// Usage: deno run --allow-read --allow-write tools/mails/render.ts [source.ts] [out dir] [fr|en]
//   source  : supabase/functions/notify/index.ts (default), or an older copy (git show <commit>:supabase/functions/notify/index.ts > old.ts)
//   out dir : where the .html files go (default /tmp/mails); PNG: node tools/mails/shoot.mjs <out dir>
// The rendering code is copied from the source (types and dates, then « e-mail » up to « jobs »), so the copy always matches the function.
const [src = "supabase/functions/notify/index.ts", out = "/tmp/mails", lang = "fr"] = Deno.args;
const code = await Deno.readTextFile(src);
const cut = (a: string, b: string) => { const i = code.indexOf(a), j = code.indexOf(b, i); if (i < 0 || j < 0) throw new Error("marker not found: " + a); return code.slice(i, j); };
const mod = `// generated by tools/mails/render.ts from ${src}
const SITE = "https://pianochallenges.com/", FN = "https://ijdxeasxmgevuchyuenn.supabase.co/functions/v1/notify", RESEND = "", FROM = "", MAX_PER_RUN = 0;
${cut("type Lang", "// ---------- data ----------")}
${cut("// ---------- e-mail ----------", "// ---------- jobs ----------")}
export { layout, welcomeMail, streakMail, weeklyMail, pathMail };`;
await Deno.mkdir(out, { recursive: true });
const modPath = `${out}/_render_module.ts`;
await Deno.writeTextFile(modPath, mod);
// deno-lint-ignore no-explicit-any
const M: any = await import("file://" + (modPath.startsWith("/") ? modPath : Deno.cwd() + "/" + modPath));
const p = { user_id: "u1", email_weekly: true, email_streak: true, email_social: true, email_news: true, lang, unsub_token: "123e4567-e89b-12d3-a456-426614174000",
  welcome_sent_at: null, last_streak_mail: null, last_weekly_mail: null };
const name = lang === "fr" ? "Camille" : "Sam";
const week = { xp: 640, days: 5, streak: 12, level: 7, toNext: 85, rank: 4, games: 3, elo: { label: lang === "fr" ? "Saute-notes · accords" : "Note Jumper · chords", r: 912, d: 38 },
  on: [true, true, false, true, true, false, true], prevXp: 520, need: 340 };
// deno-lint-ignore no-explicit-any
// the path job (lesson reminders) uses the « streak » unsubscribe category (k=streak), like jobPath in the function
const one = (kind: string, m: any) => m.cta ? M.layout(lang, p, kind === "path" ? "streak" : kind, m.subject, m.inner, m.cta, m.btn, m)
  : kind === "path" ? M.layout(lang, p, "streak", m.subject, m.inner, "https://pianochallenges.com/?from=remind", lang === "fr" ? "Reprendre" : "Pick up") // as the old job did
  : M.layout(lang, p, kind, m.subject, m.inner);
const mails: [string, string, unknown][] = [
  ["1-bienvenue", "news", M.welcomeMail(lang, p, name)],
  ["2-serie", "streak", M.streakMail(lang, name, 12)],
  ["3-recap", "weekly", M.weeklyMail(lang, name, week)],
  ["4-lecon", "path", M.pathMail(lang, name, "p04", 0, "remind")],
  ["5-place-gardee", "path", M.pathMail(lang, name, "p06", 0, "kept")],
];
const index: Record<string, { subject: string; pre: string; text: string }> = {};
for (const [file, kind, m] of mails) {
  // deno-lint-ignore no-explicit-any
  const mm = m as any, l = one(kind, mm);
  await Deno.writeTextFile(`${out}/${file}.html`, l.html);
  index[file] = { subject: mm.subject, pre: mm.pre || "", text: mm.text };
}
await Deno.writeTextFile(`${out}/index.json`, JSON.stringify(index, null, 2));
await Deno.remove(modPath);
console.log(Object.entries(index).map(([f, v]) => `${f}: ${v.subject}${v.pre ? "  |  " + v.pre : ""}`).join("\n"));
